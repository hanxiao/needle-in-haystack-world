import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless:true, args:['--no-sandbox','--use-gl=angle','--use-angle=metal','--enable-gpu','--window-size=1440,900'], defaultViewport:{width:1440,height:900}});
const page = await browser.newPage();
const logs=[]; page.on('console',m=>logs.push(`[${m.type()}] ${m.text()}`)); page.on('pageerror',e=>logs.push(`[err] ${e.message}`));
await page.goto('http://127.0.0.1:5173/', {waitUntil:'networkidle0'});
await page.waitForFunction('window.__APP__ && window.__APP__.ready===true', {timeout:60000});
await new Promise(r=>setTimeout(r,1200));
const steps = {};
steps.teleport = await page.evaluate(() => { try { return { ok:true, v: window.__APP__.qa.teleportNear('mug_white', 0.35) }; } catch(e){ return {ok:false, err:String(e)}; } });
await new Promise(r=>setTimeout(r,900));
steps.beforeGrab = await page.evaluate(() => { const A=window.__APP__; return { pos:A.state().robot.pos, canReach:A.robot.canReach ? 'yes':'no', armHeld:A.robot.arm.held, robotState:A.robot.getState(), hud:A.qa.hudText() }; });
steps.grab = await page.evaluate(() => { try { const r = window.__APP__.qa.grabByName('mug_white'); return {ok:true, r}; } catch(e){ return {ok:false, err:String(e)}; } });
await new Promise(r=>setTimeout(r,500));
steps.after = await page.evaluate(() => { const A=window.__APP__; return { held:A.robot.arm.held?.name||null, state:A.state(), hud:A.qa.hudText() }; });
console.log(JSON.stringify(steps,null,2));
console.log('LOGS', logs);
await page.screenshot({path:'qa/shots/probe3-grab.png'});
await browser.close();
