import puppeteer from 'puppeteer-core';
import { resolve } from 'node:path';
const browser = await puppeteer.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless:true, args:['--no-sandbox','--use-gl=angle','--use-angle=metal','--enable-gpu','--allow-file-access-from-files'], defaultViewport:{width:1280,height:800}});
const page = await browser.newPage();
const logs=[]; page.on('console',m=>logs.push(`[${m.type()}] ${m.text()}`)); page.on('pageerror',e=>logs.push(`[err] ${e.message}`)); page.on('requestfailed',r=>logs.push(`[fail] ${r.url()}`));
await page.goto('file://'+resolve('dist/index.html'), {waitUntil:'load', timeout:60000});
await page.waitForFunction('window.__APP__ && window.__APP__.ready===true', {timeout:60000});
await new Promise(r=>setTimeout(r,1200));
const st = await page.evaluate(()=>window.__APP__.state());
console.log(JSON.stringify({ok:true, state:st, logs},null,2));
await page.screenshot({path:'qa/shots/offline.png'});
await browser.close();
