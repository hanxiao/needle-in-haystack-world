import puppeteer from 'puppeteer-core';
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const browser = await puppeteer.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless:true, args:['--no-sandbox','--use-gl=angle','--use-angle=metal','--enable-gpu','--hide-scrollbars','--window-size=1440,900'], defaultViewport:{width:1440,height:900,deviceScaleFactor:1}});
const page = await browser.newPage(); await page.bringToFront();
await page.goto('http://127.0.0.1:4182/', {waitUntil:'networkidle0'});
await page.waitForFunction('window.__APP__ && window.__APP__.ready===true');
await wait(2200);
await page.evaluate(()=>{ const A=window.__APP__; A.qa.teleport(-3.6,-1.2,0); A.qa.setView('third'); A.qa.setCamera(Math.PI,0.16,0.95); });
await wait(800);
await page.screenshot({path:'qa/visual/shots/r5-idle2.png'});
await page.evaluate(()=>{ const A=window.__APP__; A.qa.hold('KeyW'); });
await wait(600);
await page.screenshot({path:'qa/visual/shots/r5-move2.png'});
await page.evaluate(()=>{ const A=window.__APP__; A.qa.hold('ShiftLeft'); });
await wait(600);
await page.screenshot({path:'qa/visual/shots/r5-boost2.png'});
await page.evaluate(()=>{ const A=window.__APP__; A.qa.releaseKey('KeyW'); A.qa.releaseKey('ShiftLeft'); });
console.log('ok');
await browser.close();
