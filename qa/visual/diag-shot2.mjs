import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless:true, args:['--no-sandbox','--use-gl=angle','--use-angle=metal','--enable-gpu','--window-size=1440,900'], defaultViewport:{width:1440,height:900}});
const page = await browser.newPage();
page.on('console',m=>{ if(m.type()!=='debug') console.log('LOG',m.type(),m.text()); });
await page.goto('http://127.0.0.1:4182/', {waitUntil:'networkidle0'});
await page.waitForFunction('window.__APP__ && window.__APP__.ready===true');
await new Promise(r=>setTimeout(r,2200));
const hist = `(rect)=>{const R=window.__APP__.renderer;const gl=R.getContext();const dpr=R.getPixelRatio();const x=Math.round(rect.x*dpr);const y=Math.round((window.innerHeight-rect.y-rect.h)*dpr);const w=Math.round(rect.w*dpr);const h=Math.round(rect.h*dpr);const buf=new Uint8Array(w*h*4);gl.readPixels(x,y,w,h,gl.RGBA,gl.UNSIGNED_BYTE,buf);let s=0;for(let i=0;i<buf.length;i+=4)s+=buf[i]+buf[i+1]+buf[i+2];return Math.round(s/(w*h*3));}`;
await page.screenshot({path:'qa/visual/shots/d2-0.png'});
console.log('0 mean', await page.evaluate(`(${hist})({x:0,y:0,w:1440,h:900})`));
const rects = await page.evaluate(()=>window.__APP__.qa.hudRects());
for (const p of rects.panels) console.log('panel', p.key, JSON.stringify(await page.evaluate((r)=>window.__APP__.qa.sampleHud(r), p)));
await page.screenshot({path:'qa/visual/shots/d2-1-panels.png', clip:{x:0,y:585,width:392,height:315}});
await page.screenshot({path:'qa/visual/shots/d2-2-map.png', clip:{x:1236,y:8,width:200,height:200}});
await page.screenshot({path:'qa/visual/shots/d2-3-top.png', clip:{x:0,y:0,width:460,height:120}});
await new Promise(r=>setTimeout(r,300));
await page.evaluate(()=>{ const A=window.__APP__; A.qa.teleport(-3.6,-1.2,-0.62); A.qa.setView('third'); A.qa.setCamera(-0.62,0.16,1.25); });
await new Promise(r=>setTimeout(r,700));
await page.screenshot({path:'qa/visual/shots/d2-4-room.png'});
console.log('4 mean', await page.evaluate(`(${hist})({x:0,y:0,w:1440,h:900})`));
await new Promise(r=>setTimeout(r,500));
await page.screenshot({path:'qa/visual/shots/d2-5-room.png'});
console.log('5 mean', await page.evaluate(`(${hist})({x:0,y:0,w:1440,h:900})`));
await browser.close();
